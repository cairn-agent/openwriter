// Synthetic book fixtures, in a dedicated data directory. No real documents.
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const fixture = mkdtempSync(join(tmpdir(), 'ow-outline-book-'));
process.env.OW_DATA_DIR = fixture;
const helpers = await import('../dist/server/helpers.js');
const state = await import('../dist/server/state.js');
const docs = await import('../dist/server/documents.js');
const { createOutline, outlineInfo, outlineSource } = await import('../dist/server/manuscript/outline-info.js');
const { saveViewedDocument } = await import('../dist/server/view-save.js');
const { createRevision } = await import('../dist/server/document-revisions.js');
const { parseMarkdownContent } = await import('../dist/server/compact.js');
const { tiptapToMarkdown } = await import('../dist/server/markdown.js');
helpers.ensureDataDir(); helpers.ensureWorkspacesDir();
const write = (record, body, meta = {}) => {
  const document = { type: 'doc', content: parseMarkdownContent(body) };
  writeFileSync(join(helpers.getDataDir(), record.filename), tiptapToMarkdown(document, record.title, { docId: record.docId, title: record.title, ...meta }));
  state.invalidateDocCache(record.filename);
};
try {
  const source = docs.createDocumentFile('Synthetic source');
  write(source, 'A small fictional garden.');
  const original = readFileSync(join(helpers.getDataDir(), source.filename), 'utf8');
  const outline = createOutline('Synthetic outline');
  write(outline, `## First\n\n[Source](doc:${source.docId})\n\n## Empty`, { content_type: 'manuscript' });
  let info = outlineInfo(outline.docId);
  assert.equal(info.documents, 1);
  assert.deepEqual(info.emptyChapters, ['Empty']);
  assert.equal(info.sources[0].words, 4);
  assert.equal(info.warnings.length, 0);
  assert.equal(outlineSource(source.docId).text.trim(), 'A small fictional garden.');
  const revision = info.revision;
  write(source, 'A small fictional garden grows.');
  assert.notEqual(outlineInfo(outline.docId).revision, revision, 'A source edit invalidates the reviewed build');
  writeFileSync(join(helpers.getDataDir(), source.filename), original);
  state.invalidateDocCache(source.filename);
  const manuscript = createRevision(outline.docId);
  const bookPath = join(helpers.getDataDir(), manuscript.filename);
  const frozen = readFileSync(bookPath, 'utf8');
  docs.switchDocument(outline.filename);
  const latest = { type: 'doc', content: parseMarkdownContent(`## Renamed\n\n[Source](doc:${source.docId})`) };
  state.updateDocument(latest);
  saveViewedDocument(outline.docId, state.getDocument());
  const browserDefaults = structuredClone(state.getDocument());
  browserDefaults.content.forEach(node => {
    node.attrs = { ...node.attrs, pendingStatus: null };
    if (node.type === 'paragraph' && !node.content) node.content = [];
    node.content?.forEach(child => child.marks?.forEach(mark => { if (mark.type === 'link') mark.attrs = { ...mark.attrs, target: '_blank', rel: 'noopener noreferrer', class: null }; }));
  });
  saveViewedDocument(outline.docId, browserDefaults);
  assert.equal(outlineInfo(outline.docId).chapters[0].title, 'Renamed');
  assert.throws(() => saveViewedDocument(outline.docId, { type: 'doc', content: [] }), /changed/);
  assert.throws(() => saveViewedDocument('ffffffff', state.getDocument()), /changed/);
  assert.equal(readFileSync(bookPath, 'utf8'), frozen, 'Outline edits do not synchronize the built manuscript');
  assert.equal(readFileSync(join(helpers.getDataDir(), source.filename), 'utf8'), original, 'Source body and metadata are untouched by outlining/build');
  const substantial = { type: 'doc', content: parseMarkdownContent('## Large chapter\n\nOne.\n\nTwo.\n\nThree.\n\nFour.\n\nFive.\n\nSix.') };
  state.updateDocument(substantial);
  const blank = { type: 'doc', content: [{ type: 'paragraph', attrs: { id: 'eeeeeeee' }, content: [] }] };
  assert(state.wouldCollapseBody(substantial, blank), 'Unexplained collapse is still refused');
  const removedIds = substantial.content.map(n => n.attrs.id);
  assert(state.wouldCollapseBody(substantial, blank, removedIds.slice(1)), 'Partial removal evidence cannot authorize unrelated loss');
  assert(!state.wouldCollapseBody(substantial, blank, removedIds), 'Exact human removal evidence accounts for every removed block');
  state.updateDocument(blank, removedIds);
  saveViewedDocument(outline.docId, state.getDocument());
  assert.equal(outlineInfo(outline.docId).documents, 0, 'A deliberate complete outline removal persists');
  state.updateDocument(substantial);
  state.syncBrowserDocUpdate(blank, -1, removedIds);
  saveViewedDocument(outline.docId, state.getDocument());
  assert.equal(state.getDocument().content.length, 1, 'Removal evidence survives the stale-version merge boundary');
  write(outline, '## Broken\n\n[Missing](doc:ffffffff)', { content_type: 'manuscript' });
  info = outlineInfo(outline.docId);
  assert.equal(info.sources[0].missing, true);
  assert(info.warnings.length > 0);
  console.log('PASS: accepted-text preflight, revision invalidation, confirmed saves, missing sources, source preservation and independent manuscript.');
} finally {
  state.cancelDebouncedSave();
  rmSync(fixture, { recursive: true, force: true });
}
